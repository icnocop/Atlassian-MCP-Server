<#
.SYNOPSIS
    Regenerates docs/tools.md from the [McpServerTool] attributes in the source.
.DESCRIPTION
    Run after adding, renaming, or describing a tool. A unit test fails when docs/tools.md
    does not list every tool, so the document cannot drift from the code.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'src/Atlassian.Mcp.Server'
$output = Join-Path $root 'docs/tools.md'

$toolsetTitles = [ordered]@{
    'JiraIssues'      = 'jira-issues'
    'JiraSearch'      = 'jira-search'
    'JiraComments'    = 'jira-comments'
    'JiraLinks'       = 'jira-links'
    'JiraAttachments' = 'jira-attachments'
    'JiraProjects'    = 'jira-projects'
    'JiraUsers'       = 'jira-users'
    'JiraWorklogs'    = 'jira-worklogs'
    'JiraFilters'     = 'jira-filters'
    'JiraAgile'       = 'jira-agile'
    'JiraFields'      = 'jira-fields'
    'JiraAdmin'       = 'jira-admin'
    'Confluence'      = 'confluence'
    'ConfluenceAdmin' = 'confluence-admin'
}

$tools = foreach ($file in Get-ChildItem $source -Recurse -Filter '*Tools.cs') {
    $text = Get-Content $file.FullName -Raw
    $classToolset = [regex]::Match($text, '\[Toolset\(Toolsets\.(\w+)\)\]\s*public sealed class').Groups[1].Value

    foreach ($block in ([regex]::Split($text, '(?=\[McpServerTool\()') | Select-Object -Skip 1)) {
        $header = $block.Substring(0, [Math]::Min(2000, $block.Length))
        $name = [regex]::Match($header, '\[McpServerTool\(Name = "([^"]+)"').Groups[1].Value
        $readOnly = $header -match '^\[McpServerTool\([^\]]*ReadOnly = true'
        $toolset = [regex]::Match($header, '\[Toolset\(Toolsets\.(\w+)\)\]')
        $description = [regex]::Match($header, '\]\s*\[Description\("((?:[^"\\]|\\.)*)"\)\]\s*public').Groups[1].Value -replace '\\"', '"'

        [pscustomobject]@{
            Name        = $name
            Toolset     = if ($toolset.Success) { $toolset.Groups[1].Value } else { $classToolset }
            ReadOnly    = $readOnly
            Description = $description
        }
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('# Tools')
$lines.Add('')
$lines.Add('The tools are grouped into toolsets, which the `ATLASSIAN_TOOLSETS` environment variable enables. Read-only tools change nothing; they are the only tools available when `ATLASSIAN_READ_ONLY` is `true`.')
$lines.Add('')
$lines.Add("This file is generated by ``build/Update-ToolsDoc.ps1``. It lists $($tools.Count) tools.")

foreach ($key in $toolsetTitles.Keys) {
    $group = $tools | Where-Object Toolset -eq $key | Sort-Object Name
    if (-not $group) { continue }

    $lines.Add('')
    $lines.Add("## $($toolsetTitles[$key])")
    $lines.Add('')
    $lines.Add('| Tool | Read-only | Description |')
    $lines.Add('|---|---|---|')
    foreach ($tool in $group) {
        $flag = if ($tool.ReadOnly) { 'Yes' } else { 'No' }
        $lines.Add("| ``$($tool.Name)`` | $flag | $($tool.Description -replace '\|', '\|') |")
    }
}

[System.IO.File]::WriteAllText($output, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $($tools.Count) tools to $output"
